#!/usr/bin/env python3
"""Build www/js/names.js from data/asma_ul_husna.json and data/categories.json.

Run after editing either data file:  python3 scripts/build-data.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
src = json.loads((ROOT / "data/asma_ul_husna.json").read_text(encoding="utf-8"))
cats = json.loads((ROOT / "data/categories.json").read_text(encoding="utf-8"))

names = []
for item in src["items"]:
    c = cats["names"][str(item["id"])]
    names.append({
        "n": item["id"],
        "ar": item["arabic"],
        "tr": item["transliteration"],
        "en": item["meaning"],
        "desc": item["description"],
        "refs": item["quran_references"],
        "benefits": item["benefits"],
        "note": item["reference_note"],
        "theme": c["theme"],
        "jjk": c["jjk"],
    })
assert [n["n"] for n in names] == list(range(1, 100)), "expected ids 1..99 in order"

info = {k: src[k] for k in ("title", "list_source", "collection_benefits", "verification_note")}

def js(value):
    return json.dumps(value, ensure_ascii=False, indent=2)

out = [
    "// Generated by scripts/build-data.py from data/asma_ul_husna.json and data/categories.json.",
    "// Do not edit by hand.",
    "",
    "window.THEMES = " + js(cats["themes"]) + ";",
    "",
    "window.JJK = " + js(cats["jjk"]) + ";",
    "",
    "window.INFO = " + js(info) + ";",
    "",
    "window.NAMES = [",
    ",\n".join("  " + json.dumps(n, ensure_ascii=False) for n in names),
    "];",
    "",
]
(ROOT / "www/js/names.js").write_text("\n".join(out), encoding="utf-8")
print("wrote www/js/names.js with", len(names), "names")
